import type { Integration, ProjectConfig } from "../types";

const APP_INCLUDE = [
	"app/**/*.ts",
	"app/**/*.tsx",
	"app/**/*.d.ts",
	"server/**/*.ts",
	"routes/**/*.ts",
	"middleware/**/*.ts",
	"vite.config.ts",
	"vite-env.d.ts",
];

/** Referenced projects so the editor typechecks each island extension with its JSX runtime. */
const JSX_FRAMEWORKS = [
	{
		integration: "react",
		filename: "tsconfig.react.json",
		source: "react",
		outDir: ".tsbuild/react",
		globs: ["app/**/*.react.tsx", "app/**/*.react.jsx"],
	},
	{
		integration: "solid",
		filename: "tsconfig.solid.json",
		source: "solid-js",
		outDir: ".tsbuild/solid",
		globs: ["app/**/*.solid.tsx", "app/**/*.solid.jsx"],
	},
	{
		integration: "qwik",
		filename: "tsconfig.qwik.json",
		source: "@builder.io/qwik",
		outDir: ".tsbuild/qwik",
		globs: ["app/**/*.qwik.tsx", "app/**/*.qwik.jsx"],
	},
] as const satisfies ReadonlyArray<{
	integration: Integration;
	filename: string;
	source: string;
	outDir: string;
	globs: readonly string[];
}>;

function jsxFrameworksForIntegrations(integrations: Integration[]) {
	const selected = new Set(integrations);
	return JSX_FRAMEWORKS.filter((framework) => selected.has(framework.integration));
}

function compilerOptions(jsxImportSource: string) {
	return {
		target: "ESNext",
		module: "ESNext",
		moduleResolution: "bundler",
		strict: true,
		esModuleInterop: true,
		skipLibCheck: true,
		allowArbitraryExtensions: true,
		allowImportingTsExtensions: true,
		noEmit: true,
		jsx: "react-jsx",
		// The page shell's JSX. React libraries (Radix/shadcn) typecheck
		// natively under the React engine; under Preact they resolve via compat.
		jsxImportSource,
		paths: {
			"@shared/*": ["./app/shared/*"],
			"@modules/*": ["./app/modules/*"],
		},
	};
}

export function generateTsConfig(
	core: "preact" | "react" = "preact",
	integrations: Integration[] = [],
): string {
	const jsxFrameworks = jsxFrameworksForIntegrations(integrations);
	const tsconfig = {
		compilerOptions: compilerOptions(core),
		include: APP_INCLUDE,
		exclude: jsxFrameworks.flatMap((framework) => [...framework.globs]),
		references: jsxFrameworks.map((framework) => ({ path: `./${framework.filename}` })),
	};

	return JSON.stringify(tsconfig, null, 2);
}

/** Sibling tsconfigs referenced by `generateTsConfig`. One file per JSX island extension. */
export function generateFrameworkTsConfigs(
	integrations: Integration[] = [],
): Record<string, string> {
	const files: Record<string, string> = {};
	for (const framework of jsxFrameworksForIntegrations(integrations)) {
		files[framework.filename] = JSON.stringify(
			{
				compilerOptions: {
					...compilerOptions(framework.source),
					composite: true,
					noEmit: false,
					declaration: true,
					emitDeclarationOnly: true,
					outDir: framework.outDir,
				},
				include: [...framework.globs, "app/**/*.d.ts"],
			},
			null,
			2,
		);
	}
	return files;
}

export function generateEnvDts(integrations: string[] = []): string {
	const lines: string[] = [
		`/**`,
		` * Auto-generated by create-avalon — do not edit manually.`,
		` *`,
		` * This file provides TypeScript declarations for cross-framework`,
		` * island imports, CSS modules, and Nitro virtual asset manifests.`,
		` * Re-run the scaffold to regenerate after changing integrations.`,
		` */`,
		`/// <reference types="@useavalon/avalon/types" />`,
		``,
	];

	// Cross-framework island module declarations — only for selected integrations.
	// These let TS treat cross-framework files as Preact-compatible components
	// so the island prop and component props work without manual casting.
	const frameworkModules: Record<string, { pattern: string }> = {
		vue: { pattern: "*.vue" },
		svelte: { pattern: "*.svelte" },
		solid: { pattern: "*.solid.tsx" },
		lit: { pattern: "*.lit.ts" },
		qwik: { pattern: "*.qwik.tsx" },
	};

	const selected = Object.entries(frameworkModules).filter(([name]) => integrations.includes(name));

	if (selected.length > 0) {
		for (const [, { pattern }] of selected) {
			lines.push(
				`declare module '${pattern}' {`,
				`\timport type { ComponentType } from 'preact';`,
				`\tconst component: ComponentType<Record<string, unknown>>;`,
				`\texport default component;`,
				`}`,
				``,
			);
		}
	}

	// CSS modules — always included
	lines.push(
		`declare module '*.css';`,
		`declare module '*.module.css' {`,
		`\tconst classes: Record<string, string>;`,
		`\texport default classes;`,
		`}`,
		``,
	);

	// Nitro virtual asset manifests — always included
	for (const suffix of ["client", "ssr"]) {
		lines.push(
			`declare module '*?assets=${suffix}' {`,
			`\tconst assets: {`,
			`\t\tcss: Array<{ href: string; [key: string]: string }>;`,
			`\t\tjs: Array<{ href: string; [key: string]: string }>;`,
			`\t\tentry: string;`,
			`\t\tmerge(other: unknown): typeof assets;`,
			`\t};`,
			`\texport default assets;`,
			`}`,
			``,
		);
	}

	return lines.join("\n");
}

/** Ambient types for `vite.config.ts` (Node built-ins and optional Vite plugins). */
export function generateViteEnvDts(config: ProjectConfig): string {
	const lines: string[] = [
		`/**`,
		` * Auto-generated by create-avalon — do not edit manually.`,
		` * Types for vite.config.ts (Node APIs and Vite plugins).`,
		` */`,
		`/// <reference types="node" />`,
		``,
	];

	const pushVitePluginModule = (moduleName: string, exportLine: string) => {
		lines.push(
			`declare module '${moduleName}' {`,
			`\timport type { Plugin } from 'vite';`,
			`\t${exportLine}`,
			`}`,
			``,
		);
	};

	if (config.plugins.includes("seo")) {
		pushVitePluginModule(
			"@useavalon/seo",
			"export function seo(options?: Record<string, unknown>): Plugin;",
		);
	}
	if (config.plugins.includes("agent-optimization")) {
		pushVitePluginModule(
			"@useavalon/agent-optimization",
			"export function agentOptimization(options?: Record<string, unknown>): Plugin;",
		);
	}
	if (config.styling === "tailwind" || config.styling === "shadcn") {
		pushVitePluginModule("@tailwindcss/vite", "export default function tailwindcss(): Plugin;");
	}

	return lines.join("\n");
}
