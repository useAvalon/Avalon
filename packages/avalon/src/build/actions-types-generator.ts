/**
 * Server Actions — type generation.
 *
 * Generates an ambient declaration that types `avalon/actions` (and the
 * `virtual:avalon/actions` alias) against the project's `server` export, giving
 * full input/output inference on the `actions` client proxy without manual wiring.
 *
 * Mirrors the island types generator: a pure utility that writes a `.d.ts`.
 *
 * @module build/actions-types-generator
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** Candidate extensions for the actions entry, in resolution order. */
const ENTRY_EXTENSIONS = ["ts", "tsx", "js", "jsx", "mts", "mjs"] as const;

/** Result of an actions type-generation pass. */
export interface ActionsTypeGenerationResult {
	/** Whether an actions entry was found and a declaration written. */
	generated: boolean;
	/** The absolute path of the written declaration, when generated. */
	outputPath?: string;
	/** The actions entry directory base (`app` or `src`), when found. */
	base?: "app" | "src";
}

/**
 * Locates the actions entry under the project root. Returns the base directory
 * (`app`/`src`) and the entry filename (e.g. `index.ts`), or `undefined`.
 */
export function findActionsEntryInfo(
	projectRoot: string,
): { base: "app" | "src"; file: string } | undefined {
	for (const base of ["app", "src"] as const) {
		for (const ext of ENTRY_EXTENSIONS) {
			const file = `index.${ext}`;
			if (existsSync(join(projectRoot, base, "actions", file))) {
				return { base, file };
			}
		}
	}
	return undefined;
}

/** The marker line so we can detect and avoid rewriting unchanged files. */
const HEADER =
	"// AUTO-GENERATED by Avalon — do not edit. Types `avalon/actions` and `virtual:avalon/actions`.";

function actionsModuleDeclaration(specifier: string): string {
	return `declare module ${JSON.stringify(specifier)} {
	type Server = (typeof import("./actions/index"))["server"];
	export const actions: import("@useavalon/avalon/actions").ActionClient<Server>;
	export default actions;
}`;
}

/**
 * Generates `<base>/avalon-actions.d.ts` typing `avalon/actions` against
 * the project's `server` export. `virtual:avalon/actions` is the same module.
 * No-op (returns `{ generated: false }`) when no actions entry exists — the
 * loose ambient declaration in `virtual-modules.d.ts` covers that case without
 * producing spurious type errors.
 *
 * @param projectRoot - Absolute path to the project root.
 */
export function generateActionTypes(projectRoot: string): ActionsTypeGenerationResult {
	const info = findActionsEntryInfo(projectRoot);
	if (!info) return { generated: false };

	const outputPath = join(projectRoot, info.base, "avalon-actions.d.ts");
	// The entry lives at `<base>/actions/index.*`; relative to `<base>/` the
	// import specifier is `./actions/index` (extension omitted for TS resolution).
	const content = `${HEADER}
${actionsModuleDeclaration("avalon/actions")}

${actionsModuleDeclaration("virtual:avalon/actions")}
`;

	// Avoid needless writes (which would retrigger watchers) when unchanged.
	try {
		if (existsSync(outputPath) && readFileSync(outputPath, "utf8") === content) {
			return { generated: true, outputPath, base: info.base };
		}
	} catch {
		// fall through to write
	}

	try {
		writeFileSync(outputPath, content, "utf8");
	} catch {
		return { generated: false };
	}

	return { generated: true, outputPath, base: info.base };
}

/** Returns the directory that should be watched for actions entry changes. */
export function getActionsWatchDir(projectRoot: string): string | undefined {
	const info = findActionsEntryInfo(projectRoot);
	if (!info) return undefined;
	return dirname(join(projectRoot, info.base, "actions", info.file));
}
